  async syncRealAuthorsAndPublishers() {
    try {
      const nullBooks = await this.prisma.book.findMany({
        where: {
          OR: [
            { authorId: null },
            { publisherId: null },
          ],
        },
        select: { id: true, title: true, slug: true, storeId: true, authorId: true, publisherId: true },
      });
      if (!nullBooks || nullBooks.length === 0) return;

      for (const b of nullBooks) {
        if (!b.authorId) {
          const match = TITLE_TO_AUTHOR_MAPPINGS.find(m => b.title?.includes(m.match) || b.slug?.includes(m.match));
          if (match) {
            let author = await this.prisma.author.findFirst({
              where: {
                OR: [
                  { name: { equals: match.author, mode: 'insensitive' } },
                  { slug: match.slug },
                ],
              },
            });
            if (!author) {
              const norm = match.author.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '').trim();
              author = await this.prisma.author.create({
                data: {
                  name: match.author,
                  normalizedName: norm,
                  slug: match.slug,
                  bio: match.bio,
                },
              }).catch(() => null);
            }
            if (author) {
              await this.prisma.book.update({
                where: { id: b.id },
                data: { authorId: author.id },
              }).catch(() => null);
            }
          }
        }

        if (!b.publisherId) {
          let publisher = await this.prisma.publisher.findFirst({
            where: {
              OR: [
                { slug: 'nha-nam-books' },
                { name: { contains: 'Nhã Nam', mode: 'insensitive' } },
                { slug: 'first-news-tri-viet' },
                { name: { contains: 'First News', mode: 'insensitive' } },
              ],
            },
          });
          if (!publisher) {
            publisher = await this.prisma.publisher.findFirst();
          }
          if (publisher) {
            await this.prisma.book.update({
              where: { id: b.id },
              data: { publisherId: publisher.id },
            }).catch(() => null);
          }
        }
      }
    } catch (err: any) {
      console.warn('[BooksService] syncRealAuthorsAndPublishers error:', err?.message || err);
    }
  }

  async syncRealPdfKeys() {
    for (const [slug, pdfKey] of Object.entries(REAL_EBOOK_MAPPINGS)) {
      const book = await this.prisma.book.findFirst({
        where: { slug },
        include: { digitalDetails: true },
      });
      if (book) {
        if (!book.digitalDetails) {
          await this.prisma.digitalBookDetails.create({
            data: {
              bookId: book.id,
              pdfKey,
              digitalEnabled: true,
              accessType: 'FREE',
            },
          }).catch(() => null);
        } else if (book.digitalDetails.pdfKey !== pdfKey) {
          await this.prisma.digitalBookDetails.update({
            where: { bookId: book.id },
            data: { pdfKey, digitalEnabled: true },
          }).catch(() => null);
        }
      }
    }
  }

